int main(int argc, char **argv) {
  InitLLVM X(argc, argv);
  cl::ParseCommandLineOptions(argc, argv, "oneJDK-25 TableGen MachNode Backend\n");
  return TableGenMain(argv[0], &HotSpotTableGenMain);
}
