// ===============================================================
// Replaces adlc (Architecture Description Language Compiler) with LLVM TableGen.
// Emits .inc files for HotSpot C2 MachNode classes, register masks, and matcher rules.
//
// Output modes:
//   -gen-machnode        : Emits GenMachNode.inc (MachNode class declarations)
//   -gen-reginfo         : Emits GenRegisterInfo.inc (RegMasks and register sets)
//   -gen-pattern-matching: Emits GenPatternMatching.inc (C2 Ideal -> MachNode rules)
//   -gen-callingconv     : Emits GenCallingConv.inc (Calling convention registers)
//   -gen-c2-globals      : Emits GenC2Globals.inc (C2 architecture constants)
//   -gen-macroassembler  : Emits GenMacroAssembler.inc (MacroAssembler stubs)
//   -gen-all             : Emits all .inc files to -output-dir
//

