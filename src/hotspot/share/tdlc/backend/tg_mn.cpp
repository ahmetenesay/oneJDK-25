// ============================================================================
// TableGen Main Entry Callback
// ============================================================================

bool HotSpotTableGenMain(raw_ostream &OS, const RecordKeeper &Records) {
  switch (Action) {
    case GenMachNode:
      emitMachNodeHeader(OS, Records);
      break;
    case GenRegisterInfo:
      emitRegisterInfo(OS, Records);
      break;
    case GenPatternMatching:
      emitPatternMatching(OS, Records);
      break;
    case GenCallingConv:
      emitCallingConv(OS, Records);
      break;
    case GenC2Globals:
      emitC2Globals(OS, Records);
      break;
    case GenMacroAssembler:
      emitMacroAssembler(OS, Records);
      break;
    case GenAll: {
      std::error_code EC;
      std::string Prefix = OutputDir + "/" + TargetArch.getValue() + "Gen";
      
      {
        raw_fd_ostream F(Prefix + "MachNode.inc", EC);
        if (!EC) emitMachNodeHeader(F, Records);
      }
      {
        raw_fd_ostream F(Prefix + "RegisterInfo.inc", EC);
        if (!EC) emitRegisterInfo(F, Records);
      }
      {
        raw_fd_ostream F(Prefix + "PatternMatching.inc", EC);
        if (!EC) emitPatternMatching(F, Records);
      }
      {
        raw_fd_ostream F(Prefix + "CallingConv.inc", EC);
        if (!EC) emitCallingConv(F, Records);
      }
      {
        raw_fd_ostream F(Prefix + "C2Globals.inc", EC);
        if (!EC) emitC2Globals(F, Records);
      }
      {
        raw_fd_ostream F(Prefix + "MacroAssembler.inc", EC);
        if (!EC) emitMacroAssembler(F, Records);
      }
      OS << "✅ Successfully generated all " << TargetArch << " .inc files in: " << OutputDir << "\n";
      break;
    }
    default:
      emitMachNodeHeader(OS, Records);
      break;
  }
  return false;
}

