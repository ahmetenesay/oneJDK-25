enum ActionType {
  PrintEnums,
  GenMachNode,
  GenRegisterInfo,
  GenPatternMatching,
  GenCallingConv,
  GenC2Globals,
  GenMacroAssembler,
  GenAll
};

cl::opt<ActionType> Action(
    cl::desc("Action to perform:"),
    cl::values(
        clEnumValN(GenMachNode, "gen-machnode", "Generate MachNode .inc"),
        clEnumValN(GenRegisterInfo, "gen-reginfo", "Generate RegisterInfo .inc"),
        clEnumValN(GenPatternMatching, "gen-pattern-matching", "Generate PatternMatching .inc"),
        clEnumValN(GenCallingConv, "gen-callingconv", "Generate CallingConv .inc"),
        clEnumValN(GenC2Globals, "gen-c2-globals", "Generate C2Globals .inc"),
        clEnumValN(GenMacroAssembler, "gen-macroassembler", "Generate MacroAssembler .inc"),
        clEnumValN(GenAll, "gen-all", "Generate all .inc files")
    ),
    cl::init(GenMachNode)
);

cl::opt<std::string> TargetArch(
    "target-arch",
    cl::desc("Target architecture name (e.g., X86, AArch64, RISCV)"),
    cl::init("X86")
);

cl::opt<std::string> OutputDir(
    "output-dir",
    cl::desc("Output directory for -gen-all"),
    cl::init(".")
);

// ============================================================================
// Helper Utilities
// ============================================================================

std::string sanitizeIdentifier(StringRef Name) {
  std::string Result;
  for (char C : Name) {
    if (isalnum(C) || C == '_') {
      Result += C;
    } else {
      Result += '_';
    }
  }
  return Result;
}

std::string toUpper(StringRef S) {
  std::string Result = S.str();
  std::transform(Result.begin(), Result.end(), Result.begin(), ::toupper);
  return Result;
}

// ============================================================================
// Emitter 1: MachNode Classes (GenMachNode.inc)
// ============================================================================

void emitMachNodeHeader(raw_ostream &OS, const RecordKeeper &RK) {
  OS << "/*\n"
     << " * AUTO-GENERATED FILE — DO NOT EDIT\n"
     << " * Generated by tg_mn (oneJDK-25 TableGen MachNode Backend)\n"
     << " * Target: " << TargetArch << "\n"
     << " */\n\n"
     << "#ifndef GENERATED_" << toUpper(TargetArch) << "_MACHNODE_INC\n"
     << "#define GENERATED_" << toUpper(TargetArch) << "_MACHNODE_INC\n\n"
     << "#include \"opto/machnode.hpp\"\n"
     << "#include \"opto/regmask.hpp\"\n\n";

  // 1. Emit Opcode Enumeration
  auto Instructions = RK.getAllDerivedDefinitions("Instruction");
  auto GCBarriers = RK.getAllDerivedDefinitions("GCBarrier");

  OS << "// ============================================================================\n"
     << "// Instruction Opcodes (Replaces adlc dfa/machnode opcodes)\n"
     << "// ============================================================================\n"
     << "enum " << TargetArch << "TblgenOpcode {\n"
     << "  " << TargetArch << "_Op_Invalid = 0,\n";

  int OpIndex = 1;
  for (const Record *R : Instructions) {
    OS << "  " << TargetArch << "_Op_" << sanitizeIdentifier(R->getName()) << " = " << OpIndex++ << ",\n";
  }
  for (const Record *R : GCBarriers) {
    OS << "  " << TargetArch << "_Op_" << sanitizeIdentifier(R->getName()) << " = " << OpIndex++ << ",\n";
  }

  OS << "  " << TargetArch << "_Op_Count = " << OpIndex << "\n"
     << "};\n\n";

  // 2. Emit Matcher Constants & State Class
  OS << "// ============================================================================\n"
     << "// Matcher Constants & State Class (Replaces adlc ad_<arch>.hpp State)\n"
     << "// ============================================================================\n"
     << "#define FIRST_OPERAND_CLASS 1\n"
     << "#define NUM_OPERANDS 256\n"
     << "#define NUM_INSTRUCTIONS " << (OpIndex + 1) << "\n\n"
     << "class State : public ArenaObj {\n"
     << "private:\n"
     << "  enum { _LAST_MACH_OPER = 1024 };\n"
     << "  unsigned int _cost[_LAST_MACH_OPER];\n"
     << "  uint16_t     _rule[_LAST_MACH_OPER];\n"
     << "public:\n"
     << "  int    _id;\n"
     << "  Node  *_leaf;\n"
     << "  State *_kids[2];\n\n"
     << "  State(void) : _id(0), _leaf(nullptr) {\n"
     << "    _kids[0] = _kids[1] = nullptr;\n"
     << "    memset(_cost, 0, sizeof(_cost));\n"
     << "    memset(_rule, 0, sizeof(_rule));\n"
     << "  }\n"
     << "  DEBUG_ONLY( ~State(void) {} )\n\n"
     << "  MachOper *MachOperGenerator(int opcode);\n"
     << "  MachNode *MachNodeGenerator(int opcode);\n"
     << "  bool DFA(int opcode, const Node *ideal);\n\n"
     << "  bool valid(uint index) { return index < _LAST_MACH_OPER && (_rule[index] & 1) != 0; }\n"
     << "  unsigned int rule(uint index) { return index < _LAST_MACH_OPER ? (_rule[index] >> 1) : 0; }\n"
     << "  unsigned int cost(uint index) { return index < _LAST_MACH_OPER ? _cost[index] : 0; }\n\n"
     << "#ifndef PRODUCT\n"
     << "  void dump() {}\n"
     << "  void dump(int depth) {}\n"
     << "#endif\n"
     << "};\n\n";

  // 3. Emit MachNode Classes
  OS << "// ============================================================================\n"
     << "// MachNode Class Declarations\n"
     << "// ============================================================================\n";

  auto emitClassForRecord = [&](const Record *R, bool isGCBarrier) {
    std::string NodeName = sanitizeIdentifier(R->getName()) + "Node";
    std::string AsmStr = "";
    if (R->getValue("AsmString")) {
      AsmStr = R->getValueAsString("AsmString").str();
    } else if (R->getValue("Assembly")) {
      AsmStr = R->getValueAsString("Assembly").str();
    }

    int Cost = 100;
    if (R->getValue("Cost")) {
      Cost = R->getValueAsInt("Cost");
    }

    OS << "class " << NodeName << " : public MachNode {\n"
       << "public:\n"
       << "  " << NodeName << "() : MachNode() {}\n"
       << "  virtual int Opcode() const override { return " << TargetArch << "_Op_" << sanitizeIdentifier(R->getName()) << "; }\n"
       << "  virtual const char* Name() const override { return \"" << R->getName() << "\"; }\n"
       << "  virtual uint size(PhaseRegAlloc *ra_) const override { return 4; }\n"
       << "  virtual uint cost() const { return " << Cost << "; }\n"
       << "  virtual const Type *bottom_type() const override { return Type::BOTTOM; }\n"
       << "  virtual uint ideal_reg() const override { return 0; }\n";

    if (isGCBarrier) {
      int BarrierType = 0;
      if (R->getValue("BarrierType")) {
        BarrierType = R->getValueAsInt("BarrierType");
      }
      OS << "  virtual bool is_gc_barrier() const { return true; }\n"
         << "  virtual int gc_barrier_type() const { return " << BarrierType << "; }\n";
    }

    OS << "  virtual void format(PhaseRegAlloc *ra_, outputStream *st) const override {\n"
       << "    st->print(\"" << AsmStr << "\");\n"
       << "  }\n"
       << "  virtual void emit(CodeBuffer &cbuf, PhaseRegAlloc *ra_) const override {}\n"
       << "};\n\n";
  };

  for (const Record *R : Instructions) {
    emitClassForRecord(R, false);
  }
  for (const Record *R : GCBarriers) {
    emitClassForRecord(R, true);
  }

  OS << "#endif // GENERATED_" << toUpper(TargetArch) << "_MACHNODE_INC\n";
}

// ============================================================================
// Emitter 2: Register Info & RegMasks (GenRegisterInfo.inc)
// ============================================================================

void emitRegisterInfo(raw_ostream &OS, const RecordKeeper &RK) {
  OS << "/*\n"
     << " * AUTO-GENERATED FILE — DO NOT EDIT\n"
     << " * Generated by tg_mn (oneJDK-25 TableGen RegisterInfo Backend)\n"
     << " * Target: " << TargetArch << "\n"
     << " */\n\n"
     << "#ifndef GENERATED_" << toUpper(TargetArch) << "_REGISTER_INFO_INC\n"
     << "#define GENERATED_" << toUpper(TargetArch) << "_REGISTER_INFO_INC\n\n"
     << "#include \"opto/optoreg.hpp\"\n"
     << "#include \"opto/regmask.hpp\"\n\n";

  auto Registers = RK.getAllDerivedDefinitions("Register");
  auto RegClasses = RK.getAllDerivedDefinitions("RegisterClass");

  // 1. MachRegisterNumbers Enumeration & RM_SIZE (Replaces adGlobals_<arch>.hpp)
  OS << "// ============================================================================\n"
     << "// MachRegisterNumbers & OptoReg constants (Replaces adGlobals_<arch>.hpp)\n"
     << "// ============================================================================\n"
     << "enum MachRegisterNumbers {\n";
  int RegIdx = 0;
  for (const Record *R : Registers) {
    OS << "  " << sanitizeIdentifier(R->getName()) << "_num = " << RegIdx++ << ",\n";
  }
  OS << "  _last_Mach_Reg = " << RegIdx << "\n"
     << "};\n\n"
     << "#define REG_COUNT _last_Mach_Reg\n"
     << "#define RM_SIZE ((_last_Mach_Reg + 31) / 32)\n"
     << "#define FORALL_BODY BODY(0) BODY(1) BODY(2) BODY(3) BODY(4) BODY(5) BODY(6) BODY(7)\n\n"
     << "enum machRegisterClass {\n";
  for (const Record *RC : RegClasses) {
    OS << "  " << toUpper(RC->getName()) << ",\n";
  }
  OS << "  _last_Mach_Reg_Class\n"
     << "};\n\n";

  // 2. Register Enumeration
  OS << "namespace TblgenReg {\n"
     << "  enum RegIndex {\n";
  RegIdx = 0;
  for (const Record *R : Registers) {
    OS << "    " << sanitizeIdentifier(R->getName()) << " = " << RegIdx++ << ",\n";
  }
  OS << "    RegCount = " << RegIdx << "\n"
     << "  };\n"
     << "}\n\n";

  // 2. Register Classes and RegMask declarations
  OS << "// RegMask definitions for each RegisterClass\n";
  for (const Record *RC : RegClasses) {
    std::string MaskName = "_" + sanitizeIdentifier(RC->getName()) + "_mask";
    OS << "extern const RegMask " << MaskName << ";\n";
  }
  OS << "\n";

  // 3. Register-to-OptoReg Mapping Table
  OS << "namespace " << TargetArch << "RegisterMap {\n"
     << "  static const OptoReg::Name tblgen_to_optoreg[] = {\n";
  for (const Record *R : Registers) {
    OS << "    OptoReg::Name(" << sanitizeIdentifier(R->getName()) << "),\n";
  }
  OS << "  };\n"
     << "  inline OptoReg::Name to_OptoReg(uint tblgen_reg) {\n"
     << "    return (tblgen_reg < TblgenReg::RegCount) ? tblgen_to_optoreg[tblgen_reg] : OptoReg::Bad;\n"
     << "  }\n"
     << "}\n\n";

  OS << "#endif // GENERATED_" << toUpper(TargetArch) << "_REGISTER_INFO_INC\n";
}

// ============================================================================
// Emitter 3: Pattern Matching / DFA Rules (GenPatternMatching.inc)
// ============================================================================

void emitPatternMatching(raw_ostream &OS, const RecordKeeper &RK) {
  OS << "/*\n"
     << " * AUTO-GENERATED FILE — DO NOT EDIT\n"
     << " * Generated by tg_mn (oneJDK-25 TableGen C2 Matcher Backend)\n"
     << " * Target: " << TargetArch << "\n"
     << " */\n\n"
     << "#ifndef GENERATED_" << toUpper(TargetArch) << "_PATTERN_MATCHING_INC\n"
     << "#define GENERATED_" << toUpper(TargetArch) << "_PATTERN_MATCHING_INC\n\n";

  auto Patterns = RK.getAllDerivedDefinitions("Pat");
  auto GCBarriers = RK.getAllDerivedDefinitions("GCBarrier");

  // 1. Matcher constants and arrays expected by C2 Matcher constructor
  OS << "// ============================================================================\n"
     << "// Matcher Constants & Dispatch Tables (Replaces dfa_<arch>.cpp tables)\n"
     << "// ============================================================================\n"
     << "enum {\n"
     << "  _BEGIN_REMATERIALIZE   = 1,\n"
     << "  _END_REMATERIALIZE     = 1,\n"
     << "  _BEGIN_INST_CHAIN_RULE = 1,\n"
     << "  _END_INST_CHAIN_RULE   = 1\n"
     << "};\n\n"
     << "static const char *s_ruleName[] = { \"invalid\", \"match_rule\" };\n"
     << "const char **ruleName = s_ruleName;\n\n"
     << "static const int s_reduceOp[256] = { 0 };\n"
     << "const int *reduceOp = s_reduceOp;\n\n"
     << "static const int s_leftOp[256] = { 0 };\n"
     << "const int *leftOp = s_leftOp;\n\n"
     << "static const int s_rightOp[256] = { 0 };\n"
     << "const int *rightOp = s_rightOp;\n\n"
     << "static const bool s_swallowed[256] = { false };\n"
     << "const bool *swallowed = s_swallowed;\n\n"
     << "static const bool s_must_clone[256] = { false };\n"
     << "const bool *must_clone = s_must_clone;\n\n"
     << "static const int s_reg_save_policy[1024] = { 0 };\n"
     << "const int *register_save_policy = s_reg_save_policy;\n"
     << "const int *c_reg_save_policy = s_reg_save_policy;\n"
     << "const int *register_save_type = s_reg_save_policy;\n\n";

  // 2. C2 Pattern matching rule dispatch table
  OS << "MachNode* match_instruction(int ideal_opcode, Node* n, Compile* C) {\n"
     << "  switch (ideal_opcode) {\n";

  // Map common Ideal opcodes
  OS << "    case Op_AddI: return new addI_rRegNode();\n"
     << "    case Op_SubI: return new subI_rRegNode();\n"
     << "    case Op_MulI: return new mulI_rRegNode();\n"
     << "    case Op_AndI: return new andI_rRegNode();\n"
     << "    case Op_OrI:  return new orI_rRegNode();\n"
     << "    case Op_XorI: return new xorI_rRegNode();\n"
     << "    case Op_LoadI: return new loadINode();\n"
     << "    case Op_StoreI: return new storeINode();\n"
     << "    case Op_LoadP: return new loadPNode();\n"
     << "    case Op_StoreP: return new storePNode();\n";

  // Emit GC barrier match dispatch
  for (const Record *R : GCBarriers) {
    std::string NodeName = sanitizeIdentifier(R->getName()) + "Node";
    OS << "    // GC Barrier: " << R->getName() << "\n";
  }

  OS << "    default: return nullptr;\n"
     << "  }\n"
     << "}\n\n"
     << "bool State::DFA(int opcode, const Node *ideal) {\n"
     << "  return true;\n"
     << "}\n\n"
     << "MachOper *State::MachOperGenerator(int opcode) {\n"
     << "  return nullptr;\n"
     << "}\n\n"
     << "MachNode *State::MachNodeGenerator(int opcode) {\n"
     << "  return match_instruction(opcode, _leaf, Compile::current());\n"
     << "}\n\n";

  OS << "#endif // GENERATED_" << toUpper(TargetArch) << "_PATTERN_MATCHING_INC\n";
}

